"""Generate a TypeScript schema contract directly from FastAPI's OpenAPI schema."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps" / "api" / "src"))

from fleet.api.main import app  # noqa: E402


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return f'ApiSchemas["{name}"]'
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(ts_type(item) for item in schema[key])
    if "allOf" in schema:
        return " & ".join(ts_type(item) for item in schema["allOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        properties = schema.get("properties", {})
        if not properties:
            additional = schema.get("additionalProperties", True)
            return (
                f"Record<string, {ts_type(additional)}>"
                if isinstance(additional, dict)
                else "Record<string, unknown>"
            )
        required = set(schema.get("required", []))
        lines = ["{"]
        for key, child in properties.items():
            optional = "" if key in required else "?"
            lines.append(f"    {json.dumps(key)}{optional}: {ts_type(child)};")
        lines.append("  }")
        return "\n  ".join(lines)
    if kind == "string":
        return "string"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    return "unknown"


def render() -> str:
    schema = app.openapi()
    definitions = schema.get("components", {}).get("schemas", {})
    lines = [
        "/* Generated by scripts/generate_openapi_types.py; do not edit manually. */",
        "export type ApiSchemas = {",
    ]
    for name, definition in sorted(definitions.items()):
        lines.append(f"  {json.dumps(name)}: {ts_type(definition)};")
    lines.extend(["};", ""])
    for name in sorted(definitions):
        lines.append(f"export type {name} = ApiSchemas[{json.dumps(name)}];")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    destination = ROOT / "apps" / "web" / "src" / "lib" / "api-openapi.ts"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(render(), encoding="utf-8")
    print(f"Generated {destination.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
